<?php
require_once __DIR__ . '/booking.php';

function printAssetBase() {
    $script = str_replace('\\', '/', (string)($_SERVER['SCRIPT_NAME'] ?? ''));
    if (preg_match('#/(admin|dentist|patient)/#', $script)) {
        return '../';
    }
    return '';
}

function printLetterheadHtml() {
    $h = clinicLetterhead();
    $logo = printAssetBase() . 'assets/images/logobluetransparent.png';
    $html = '<header class="print-letterhead">';
    $html .= '<img class="print-logo" src="' . htmlspecialchars($logo, ENT_QUOTES, 'UTF-8') . '" alt="Denthub" onerror="this.style.display=\'none\'">';
    $html .= '<div class="print-mark">DENTHUB DENTAL CLINIC</div>';
    $html .= '<h1>' . htmlspecialchars($h['name']) . '</h1>';
    $parts = array_filter([$h['branch'], $h['address']]);
    if ($parts) {
        $html .= '<p>' . htmlspecialchars(implode(' · ', $parts)) . '</p>';
    }
    $contact = array_filter([$h['phone'] ? 'Tel: ' . $h['phone'] : '', $h['email'] ? 'Email: ' . $h['email'] : '']);
    if ($contact) {
        $html .= '<p>' . htmlspecialchars(implode(' · ', $contact)) . '</p>';
    }
    $html .= '<p class="print-meta">Official clinic document · Generated ' . htmlspecialchars($h['generated']) . '</p>';
    $html .= '</header>';
    return $html;
}

function appointmentPrintRows($appointment) {
    $rows = [
        'Reference' => $appointment['appointment_number'] ?? '',
        'Patient' => trim(($appointment['last_name'] ?? '') . ', ' . ($appointment['first_name'] ?? '')),
        'Service' => $appointment['service_name'] ?? '',
        'Dentist' => $appointment['dentist_name'] ?? 'TBA',
        'Branch' => $appointment['branch_name'] ?? '',
        'Date' => isset($appointment['appointment_date']) ? formatDate($appointment['appointment_date']) : '',
        'Time' => isset($appointment['appointment_time']) ? formatTime($appointment['appointment_time']) : '',
        'Status' => ucfirst(str_replace('_', ' ', (string)($appointment['status'] ?? ''))),
        'Reason for visit' => $appointment['reason_for_visit'] ?? '',
    ];
    $html = '<table class="print-kv"><tbody>';
    foreach ($rows as $label => $value) {
        if ($value === '' || $value === null) {
            continue;
        }
        $html .= '<tr><th>' . htmlspecialchars($label) . '</th><td>' . htmlspecialchars((string)$value) . '</td></tr>';
    }
    $html .= '</tbody></table>';
    return $html;
}

function printDocumentStart($title, $subtitle = '') {
    $h = clinicLetterhead();
    $html = '<div class="print-document">';
    $html .= printLetterheadHtml();
    $html .= '<h2 class="print-doc-title">' . htmlspecialchars($title) . '</h2>';
    if ($subtitle !== '') {
        $html .= '<p class="print-doc-sub">' . htmlspecialchars($subtitle) . '</p>';
    }
    $html .= '<p class="print-doc-meta">Official clinic record · ' . htmlspecialchars($h['generated']) . '</p>';
    return $html;
}

function printDocumentEnd() {
    $html = '<div class="print-signature"><div><span>Prepared by / Clinic staff</span></div><div><span>Patient / Recipient</span></div></div>';
    $html .= '<p class="print-doc-footer">This document was generated by ' . htmlspecialchars(APP_NAME) . '. It is intended for clinic records and authorized recipients only.</p></div>';
    return $html;
}

function printAppointmentDocument($appointment, $title = 'Appointment record') {
    return printDocumentStart($title, $appointment['appointment_number'] ?? '')
        . appointmentPrintRows($appointment)
        . printDocumentEnd();
}

function writeCsvLetterhead($out, $title, $period = '') {
    $h = clinicLetterhead();
    fputcsv($out, [$h['name']]);
    $line = array_filter([$h['branch'], $h['address'], $h['phone'], $h['email']]);
    if ($line) {
        fputcsv($out, $line);
    }
    fputcsv($out, ['Generated', $h['generated']]);
    if ($title !== '') {
        fputcsv($out, ['Report', $title]);
    }
    if ($period !== '') {
        fputcsv($out, ['Period', $period]);
    }
    fputcsv($out, []);
}

function dashboardTrendData($dentist_id = null) {
    $db = getDB();
    $start = appTodayImmutable()->modify('-13 days')->format('Y-m-d');
    $sql = "
        SELECT appointment_date::text AS d, COUNT(*) AS c
        FROM appointments
        WHERE appointment_date >= ?
    ";
    $params = [$start];
    $types = 's';
    if ($dentist_id) {
        $sql .= " AND dentist_id = ? ";
        $params[] = (int)$dentist_id;
        $types .= 'i';
    }
    $sql .= " GROUP BY appointment_date ORDER BY appointment_date";
    $stmt = $db->prepare($sql);
    $stmt->bind_param($types, ...$params);
    $stmt->execute();
    $map = [];
    $res = $stmt->get_result();
    while ($row = $res->fetch_assoc()) {
        $map[$row['d']] = (int)$row['c'];
    }
    $labels = [];
    $values = [];
    for ($i = 13; $i >= 0; $i--) {
        $d = appTodayImmutable()->modify('-' . $i . ' days')->format('Y-m-d');
        $labels[] = $d;
        $values[] = $map[$d] ?? 0;
    }

    $statusSql = "
        SELECT status, COUNT(*) AS c
        FROM appointments
        WHERE appointment_date >= ?
    ";
    $params = [$start];
    $types = 's';
    if ($dentist_id) {
        $statusSql .= " AND dentist_id = ? ";
        $params[] = (int)$dentist_id;
        $types .= 'i';
    }
    $statusSql .= " GROUP BY status";
    $stmt = $db->prepare($statusSql);
    $stmt->bind_param($types, ...$params);
    $stmt->execute();
    $statusLabels = [];
    $statusValues = [];
    $res = $stmt->get_result();
    while ($row = $res->fetch_assoc()) {
        $statusLabels[] = ucfirst(str_replace('_', ' ', $row['status']));
        $statusValues[] = (int)$row['c'];
    }

    $svcSql = "
        SELECT s.service_name, COUNT(*) AS c
        FROM appointments a
        JOIN services s ON s.service_id = a.service_id
        WHERE a.appointment_date >= ?
    ";
    $params = [$start];
    $types = 's';
    if ($dentist_id) {
        $svcSql .= " AND a.dentist_id = ? ";
        $params[] = (int)$dentist_id;
        $types .= 'i';
    }
    $svcSql .= " GROUP BY s.service_name ORDER BY c DESC LIMIT 8";
    $stmt = $db->prepare($svcSql);
    $stmt->bind_param($types, ...$params);
    $stmt->execute();
    $serviceLabels = [];
    $serviceValues = [];
    $res = $stmt->get_result();
    while ($row = $res->fetch_assoc()) {
        $serviceLabels[] = $row['service_name'];
        $serviceValues[] = (int)$row['c'];
    }

    return [
        'trend_labels' => $labels,
        'trend_values' => $values,
        'status_labels' => $statusLabels,
        'status_values' => $statusValues,
        'service_labels' => $serviceLabels,
        'service_values' => $serviceValues,
    ];
}
